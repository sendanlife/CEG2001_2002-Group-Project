#include <msp430.h>
#include <stdint.h>
#include "buzzer.h"

/* ---- Pin: P2.4 (also Timer_A2 output TA2.1, used for passive buzzers) ---- */
#define BUZ_DIR        P2DIR
#define BUZ_OUT        P2OUT
#define BUZ_SEL        P2SEL
#define BUZ_PIN        BIT4

/* 0 = active buzzer (makes its own tone, just needs HIGH)
   1 = passive buzzer (needs a square wave, generated by Timer_A2 PWM) */
#define BUZZER_PASSIVE   0
#define BUZZER_FREQ_HZ   2000           /* tone frequency for a passive buzzer */

#define BUZ_CPU_HZ       1000000UL      /* default DCO ~1 MHz (SMCLK) */

static void delay_ms(uint16_t ms)
{
    while (ms--) {
        __delay_cycles(BUZ_CPU_HZ / 1000UL);
    }
}

void Buzzer_Init(void)
{
    BUZ_DIR |= BUZ_PIN;                 /* output */
    BUZ_OUT &= ~BUZ_PIN;                /* silent */
}

void Buzzer_On(void)
{
#if BUZZER_PASSIVE
    TA2CCR0  = (uint16_t)(BUZ_CPU_HZ / BUZZER_FREQ_HZ) - 1;   /* period     */
    TA2CCR1  = TA2CCR0 / 2;                                   /* 50% duty   */
    TA2CCTL1 = OUTMOD_7;                                      /* reset/set  */
    TA2CTL   = TASSEL_2 | MC_1 | TACLR;                       /* SMCLK, up  */
    BUZ_SEL |= BUZ_PIN;                                       /* route TA2.1 to the pin */
#else
    BUZ_OUT |= BUZ_PIN;
#endif
}

void Buzzer_Off(void)
{
#if BUZZER_PASSIVE
    TA2CTL   = MC_0;                    /* stop the timer */
    BUZ_SEL &= ~BUZ_PIN;                /* back to plain GPIO */
#endif
    BUZ_OUT &= ~BUZ_PIN;
}

void Buzzer_Beep(uint16_t on_ms)
{
    Buzzer_On();
    delay_ms(on_ms);
    Buzzer_Off();
}

void Buzzer_Pattern(uint8_t beeps, uint16_t on_ms, uint16_t off_ms)
{
    while (beeps--) {
        Buzzer_Beep(on_ms);
        delay_ms(off_ms);
    }
}
