CREATE DATABASE pillsExtraction;
USE pillsExtraction;

CREATE TABLE medicalStaff (
MSId CHAR(5) PRIMARY KEY,
NAME VARCHAR(32) NOT NULL,
email VARCHAR(128) NOT NULL UNIQUE,
phoneNumber VARCHAR(20) NOT NULL,
passwordHash VARCHAR(225) NOT NULL
);

CREATE TABLE users (
UUID CHAR(5) PRIMARY KEY,
NAME VARCHAR(32) NOT NULL, 
email VARCHAR(128) NOT NULL UNIQUE,
nric VARCHAR(9) NOT NULL UNIQUE,
phoneNumber VARCHAR(20) NOT NULL,
MSId CHAR(5),
NFCId CHAR(20) UNIQUE,
medicalHistoryId CHAR(5),

FOREIGN KEY (MSId) REFERENCES medicalStaff(MSId) ON DELETE SET NULL
);

CREATE TABLE medical (
medicalHistoryId CHAR(5) PRIMARY KEY, 
UUID CHAR(5) NOT NULL,
issueBy CHAR(5) NOT NULL,
medicalStaffName VARCHAR(32) NOT NULL,

FOREIGN KEY (UUID) REFERENCES users(UUID) ON DELETE CASCADE,
FOREIGN KEY (issueBy) REFERENCES medicalStaff(MSId) ON DELETE CASCADE
);

CREATE TABLE pill (
pillsId CHAR(5) PRIMARY KEY,
pillName CHAR(32) NOT NULL,
DESCRIPTION TEXT
);

CREATE TABLE userPill (
UUID CHAR(5) NOT NULL,
pillsId CHAR(5) NOT NULL,
quantity INT NOT NULL DEFAULT 0,
pillsDose INT NOT NULL DEFAULT 1,

PRIMARY KEY (UUID, pillsId),
FOREIGN KEY (UUID) REFERENCES users(UUID) ON DELETE CASCADE,
FOREIGN KEY (pillsId) REFERENCES pill(pillsId)
);

CREATE TABLE dispenseLog(
dispenseId CHAR(5) PRIMARY KEY,
UUID CHAR(5) NOT NULL,
pillsId CHAR(5) NOT NULL,
amountDispense INT,
STATUS BOOLEAN DEFAULT FALSE,
TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

FOREIGN KEY (UUID)		REFERENCES users(UUID) ON DELETE CASCADE,
FOREIGN KEY (pillsId)	REFERENCES pill(pillsId)
);